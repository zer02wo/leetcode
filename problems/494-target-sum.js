/**
 * @param {number[]} nums
 * @param {number} target
 * @return {number}
 */
var findTargetSumWaysMemoization = function(nums, target) {
    // memoization mapping [index][sum] -> numWaysToSumToTarget
    // allows O(1) lookups of previous results
    const memo = new Map();

    // recursive backtracking helper function
    function backtrack(index, sum) {
        // define 2D map key via string
            // TODO: is there a better way to do implement a 2D map rather than building a string key?
        const memoKey = `${index},${sum}`;

        // if key exists, this has been calculated already
        if (memo.has(memoKey)) {
            // return the existing result
            return memo.get(memoKey);
        }

        // end of branch, all nums used
        if (index === nums.length) {
            // expression generated by this branch is a valid sum
            if (sum === target) {
                return 1;
            } else {
                return 0;
            }
        }

        // recursively branch after *adding or subtracint* current element to expression
        // result is the different number of ways to sum to target
        const result = backtrack(index + 1, sum + nums[index]) + backtrack(index + 1, sum - nums[index]);

        // store result in memoization cache/map to look up later
        memo.set(memoKey, result);

        return result;
    }

    // initialise recursive backtracking function
    return backtrack(0, 0);

    // 97 ms / beats 65.09%

    // much better performance for not a lot more effort
        // although this was pretty unintuitive, hopefully becomes easier with more exposure to concept
    // TODO: feel like there's probably way to define the 2D map
};

var findTargetSumWaysBruteForce = function(nums, target) {
    let sumWays = 0;

    // recursive backtracking helper function
    function backtrack(index, sum) {
        // end of branch, all nums used
        if (index === nums.length) {
            // expression generated by this branch is a valid sum
            if (sum === target) {
                sumWays++;
            }

            return;
        }

        // recursively branch after adding current element to expression
        backtrack(index + 1, sum + nums[index]);

        // recursively branch after subtracting current element from expression
        backtrack(index + 1, sum - nums[index]);
    }

    // initialise recursive backtracking function
    backtrack(0, 0);

    return sumWays;

    // 1717 ms / beats 18.78% (first run)
    // 1682 ms / beats 26.40% (second run)

    // O(2^n) time complexity
        // creating 2 branches for every element
    // O(n) space complexity
        // recursion stack depth
        // otherwise O(1) for integer counter/output

    // surprised this was accepted instead of TLE, but it's clear that there's a better solution
    // I think the phrase "build an expression" made me think we had to output strings
        // mind clearly blanked when seeing the output in the examples...
};

